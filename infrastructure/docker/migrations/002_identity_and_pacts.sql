CREATE FUNCTION protect_evidence_version() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF ROW(NEW.evidence_id,NEW.version,NEW.object_key,NEW.content_sha256,NEW.mime_type,NEW.size_bytes) IS DISTINCT FROM ROW(OLD.evidence_id,OLD.version,OLD.object_key,OLD.content_sha256,OLD.mime_type,OLD.size_bytes) THEN RAISE EXCEPTION 'Evidence version content is immutable'; END IF;
 RETURN NEW; END $$;
